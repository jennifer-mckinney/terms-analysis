# bounded, hermetic subprocess runner
# --------------------------------------------------------------------------
class CheckFailure(AssertionError):
    """The repository is not in the state PR 1 promises."""


@dataclass(frozen=True)
class RunResult:
    returncode: int
    stdout: bytes
    stderr: bytes


def printable(data: bytes | str, limit: int) -> str:
    """Escape to printable ASCII, then truncate (output safety, F2/F8)."""
    text = data.decode("utf-8", "backslashreplace") if isinstance(data, bytes) else data
    out = "".join(ch if " " <= ch <= "~" else ch.encode("unicode_escape").decode("ascii") for ch in text)
    return out if len(out) <= limit else out[:limit] + TRUNCATED


def hermetic_env() -> dict[str, str]:
    """Inherited env minus every GIT_* knob; replace refs, grafts, config off."""
    env = {key: value for key, value in os.environ.items() if not key.startswith("GIT_")}
    env.update(
        GIT_CONFIG_NOSYSTEM="1",
        GIT_CONFIG_GLOBAL=os.devnull,
        GIT_NO_REPLACE_OBJECTS="1",
        GIT_GRAFT_FILE=os.devnull,
        GIT_TERMINAL_PROMPT="0",
        LC_ALL="C",
    )
    return env


# Repository-local config could still change what a read reports.
GIT_READ_FLAGS = (
    "--no-replace-objects",
    "-c", "core.commitGraph=false",
    "-c", "log.showSignature=false",
    "-c", "log.follow=false",
    "-c", "log.mailmap=false",
    "-c", "advice.graftFileDeprecated=false",
)


def run_bounded(
    cmd: list[str],
    *,
    cwd: Path,
    env: dict[str, str],
    cfg: LayoutConfig,
    label: str,
    input_bytes: bytes | None = None,
) -> RunResult:
    """Run cmd; fail closed past git_timeout_seconds or max_git_output_bytes."""
    cap = cfg.max_git_output_bytes
    proc = subprocess.Popen(
        cmd,
        cwd=cwd,
        env=env,
        stdin=subprocess.PIPE if input_bytes is not None else subprocess.DEVNULL,
        stdout=subprocess.PIPE,
        stderr=subprocess.PIPE,
    )
    buffers = {"stdout": bytearray(), "stderr": bytearray()}
    overflow = threading.Event()

    def pump(name: str, stream) -> None:  # type: ignore[no-untyped-def]
        buf = buffers[name]
        while chunk := stream.read1(1 << 16):
            if len(buf) + len(chunk) > cap:
                overflow.set()
                proc.kill()
                break
            buf.extend(chunk)

    pumps = [
        threading.Thread(target=pump, args=("stdout", proc.stdout), daemon=True),
        threading.Thread(target=pump, args=("stderr", proc.stderr), daemon=True),
    ]
    for thread in pumps:
        thread.start()
    if input_bytes is not None:
        assert proc.stdin is not None
        try:
            proc.stdin.write(input_bytes)
            proc.stdin.close()
        except BrokenPipeError:
            pass
    try:
        proc.wait(timeout=cfg.git_timeout_seconds)
    except subprocess.TimeoutExpired:
        proc.kill()
        proc.wait()
        raise CheckFailure(
            f"{label} timed out after {cfg.git_timeout_seconds}s "
            f"(git_timeout_seconds in {CONFIG_REL}); failing closed"
        ) from None
    for thread in pumps:
        thread.join(cfg.git_timeout_seconds)
    if overflow.is_set():
        raise CheckFailure(
            f"{label} output exceeded {cap} bytes (max_git_output_bytes in {CONFIG_REL}); failing closed"
        )
    return RunResult(proc.returncode, bytes(buffers["stdout"]), bytes(buffers["stderr"]))


@dataclass(frozen=True)
class Repo:
    path: Path
    cfg: LayoutConfig

    def mask(self, data: bytes) -> bytes:
        return data.replace(str(self.path).encode(), b"<repo>")

    def git(self, *args: str, ok: tuple[int, ...] = (0,)) -> RunResult:
        label = f"git {args[0]}"
        res = run_bounded(
            ["git", "-C", str(self.path), *GIT_READ_FLAGS, *args],
            cwd=self.path,
            env=hermetic_env(),
            cfg=self.cfg,
            label=label,
        )
        if res.returncode not in ok:
            detail = printable(self.mask(res.stderr.strip()), self.cfg.max_message_chars)
            raise CheckFailure(f"{label} exited {res.returncode}: {detail}")
        return res

    def out(self, *args: str) -> str:
        return self.git(*args).stdout.decode("ascii")


def require_full_history(repo: Repo) -> None:
    """Shallow history: fail under CI (F9), skip locally with the reason."""
    if repo.out("rev-parse", "--is-shallow-repository").strip() == "true":
        reason = (
            "shallow clone: the #125 history checks need full history "
            "(actions/checkout with fetch-depth: 0, or git fetch --unshallow)"
        )
        if os.environ.get("CI"):
            pytest.fail(reason)
        pytest.skip(reason)


# --------------------------------------------------------------------------
# git output parsing
# --------------------------------------------------------------------------
def _path(raw: bytes) -> str:
    return raw.decode("utf-8", "surrogateescape")


def parse_name_status(raw: bytes) -> list[tuple[str, str, str | None]]:
    tokens = raw.split(b"\0")
    if tokens and tokens[-1] == b"":
        tokens.pop()
    entries: list[tuple[str, str, str | None]] = []
    position = 0
    while position < len(tokens):
        status = tokens[position].decode("ascii")
        if status[:1] in ("R", "C"):
            entries.append((status, _path(tokens[position + 1]), _path(tokens[position + 2])))
            position += 3
        else:
            entries.append((status, _path(tokens[position + 1]), None))
            position += 2
    return entries


def ls_tree(repo: Repo, treeish: str) -> list[tuple[str, str, str]]:
    """(mode, type, name) of the direct entries of treeish."""
    entries = []
    for record in repo.git("ls-tree", "-z", treeish).stdout.split(b"\0"):
        if record:
            meta, name = record.split(b"\t", 1)
            mode, kind, _sha = meta.decode("ascii").split(" ")
            entries.append((mode, kind, _path(name)))
    return entries


def tip_files(repo: Repo) -> set[str]:
    raw = repo.git("ls-tree", "-r", "-z", "--name-only", repo.cfg.ingester_tip).stdout
    return {_path(item) for item in raw.split(b"\0") if item}


def tree_of(repo: Repo, treeish: str) -> str:
    res = repo.git("rev-parse", "--verify", "--quiet", treeish, ok=(0, 1, 128))
    return res.stdout.decode("ascii").strip() if res.returncode == 0 else "<missing>"


def has_commit(repo: Repo, sha: str) -> bool:
    return repo.git("cat-file", "-e", f"{sha}^{{commit}}", ok=(0, 1, 128)).returncode == 0


def is_ancestor(repo: Repo, ancestor: str, descendant: str) -> bool:
    return repo.git("merge-base", "--is-ancestor", ancestor, descendant, ok=(0, 1)).returncode == 0


def roots(repo: Repo, rev: str) -> set[str]:
    return set(repo.out("rev-list", "--max-parents=0", rev).split())


def ancestry(repo: Repo) -> list[tuple[str, tuple[str, ...]]]:
    """Commits that descend from the ingester tip and lead to HEAD, with parents."""
    out = repo.out("rev-list", "--ancestry-path", "--parents", "--topo-order", f"{repo.cfg.ingester_tip}..HEAD")
    return [(parts[0], tuple(parts[1:])) for parts in (line.split() for line in out.splitlines()) if parts]


