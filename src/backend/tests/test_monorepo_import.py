# sandbox builder (git plumbing only: no network, no hooks, no checkout)
# --------------------------------------------------------------------------
class Sandbox:
    def __init__(self, root: Path, cfg: LayoutConfig) -> None:
        self.root = root
        self.cfg = cfg
        self._blobs: dict[tuple[Path, bytes], str] = {}
        self._serial = itertools.count()

    def git(self, repo: Path, *args: str, input_bytes: bytes | None = None, env_extra: dict[str, str] | None = None) -> str:
        stamp = f"{1_700_000_000 + next(self._serial) * 60} +0000"
        env = hermetic_env() | {
            "GIT_AUTHOR_NAME": "probe",
            "GIT_AUTHOR_EMAIL": "probe@example.invalid",
            "GIT_COMMITTER_NAME": "probe",
            "GIT_COMMITTER_EMAIL": "probe@example.invalid",
            "GIT_AUTHOR_DATE": stamp,
            "GIT_COMMITTER_DATE": stamp,
        } | (env_extra or {})
        res = run_bounded(
            ["git", "-C", str(repo), "-c", "commit.gpgsign=false", "-c", "advice.graftFileDeprecated=false", *args],
            cwd=repo, env=env, cfg=self.cfg, label=f"sandbox git {args[0]}", input_bytes=input_bytes,
        )
        if res.returncode != 0:
            raise RuntimeError(f"sandbox git {args[0]} failed: {printable(res.stderr, 400)}")
        return res.stdout.decode("utf-8", "surrogateescape").strip()

    def init(self, name: str) -> Path:
        path = self.root / name
        path.mkdir()
        self.git(path, "init", "-q", "-b", "main")
        return path

    def blob(self, repo: Path, data: bytes) -> str:
        key = (repo, data)
        if key not in self._blobs:
            self._blobs[key] = self.git(repo, "hash-object", "-w", "--stdin", input_bytes=data)
        return self._blobs[key]

    def _index_env(self) -> dict[str, str]:
        return {"GIT_INDEX_FILE": str(self.root / f"index-{next(self._serial)}")}

    def tree(self, repo: Path, files: dict[str, tuple[str, bytes]], base: str | None = None) -> str:
        """Tree of base with files applied; a mode of '0' deletes the path."""
        env = self._index_env()
        if base is not None:
            self.git(repo, "read-tree", base, env_extra=env)
        records = b""
        for path, (mode, data) in files.items():
            sha = "0" * 40 if mode == "0" else self.blob(repo, data)
            records += f"{mode} {sha}\t".encode() + path.encode("utf-8", "surrogateescape") + b"\0"
        self.git(repo, "update-index", "-z", "--index-info", input_bytes=records, env_extra=env)
        return self.git(repo, "write-tree", env_extra=env)

    def commit(self, repo: Path, tree: str, parents: list[str], message: str) -> str:
        args = ["commit-tree", tree]
        for parent in parents:
            args += ["-p", parent]
        return self.git(repo, *args, "-m", message)

    def nest(self, repo: Path, prefix: str, subtree: str) -> str:
        for segment in reversed(prefix.split("/")):
            subtree = self.git(repo, "mktree", input_bytes=f"040000 tree {subtree}\t{segment}\n".encode())
        return subtree

    def graft(self, repo: Path, base_commit: str, prefix: str, subtree: str) -> str:
        """base_commit's tree with prefix replaced by subtree (what the merge records)."""
        env = self._index_env()
        self.git(repo, "read-tree", base_commit, env_extra=env)
        self.git(repo, "rm", "--cached", "-r", "-q", "--ignore-unmatch", "--", prefix, env_extra=env)
        self.git(repo, "read-tree", f"--prefix={prefix}/", subtree, env_extra=env)
        return self.git(repo, "write-tree", env_extra=env)

    def set_head(self, repo: Path, commit: str) -> None:
        self.git(repo, "update-ref", "refs/heads/main", commit)


def hostile_names() -> list[str]:
    """One file name per hostile character, plus invalid UTF-8 and a leading dash."""
    names = [f"name-{index:02d}-{char}-x.txt" for index, char in enumerate(HOSTILE_CHARS) if char != "\x00"]
    return names + ["-leading-dash.txt", "bad-utf8-\udcff.txt", "quote-'-\"-\\.txt", "x" * 300]


def leak_sample() -> bytes:
    """First `block` vector of the scanner's own table, tokens expanded."""
    spec = importlib.util.spec_from_file_location("leak_scan_for_125", LEAK_SCAN_PY)
    assert spec is not None and spec.loader is not None
    module: ModuleType = importlib.util.module_from_spec(spec)
    spec.loader.exec_module(module)
    for line in (REPO_ROOT / LEAK_VECTORS_REL).read_text(encoding="utf-8").splitlines():
        cols = line.split("\t")
        if not line.startswith("#") and len(cols) >= 3 and cols[0] == "block":
            return (module.expand_vector_tokens(cols[2]) + "\n").encode("utf-8")
    raise AssertionError(f"{LEAK_VECTORS_REL} has no block vector")


@dataclass(frozen=True)
class Ingester:
    path: Path
    root: str
    tip: str
    leaks: tuple[str, ...] = ()  # commits whose own diff adds a leak, known by construction


def build_ingester(
    sb: Sandbox, name: str, *, leak_in_history: bool, late_leak: bool = False, merged_leak: bool = False
) -> Ingester:
    """leak_in_history: a mainline commit adds a leak that a later commit deletes.
    late_leak: a further commit on top of the merge tip adds a new leak.
    merged_leak: a side-branch commit adds a leak and the tip merge carries it
    in again (its first-parent diff adds the file), like ingester 091f29b."""
    repo = sb.init(name)
    files: dict[str, tuple[str, bytes]] = {
        "README.md": ("100644", b"ingester\n"),
        "src/ingester/__init__.py": ("100644", b""),
        "tests/__init__.py": ("100644", b""),  # identical blobs: rename pairing can cross dirs
        "scripts/run.sh": ("100755", b"#!/bin/sh\nexit 0\n"),
        "docs/link": ("120000", b"../README.md"),
        ".hidden": ("100644", b"dotfile\n"),
        "docs/evidence/clean.md": ("100644", b"scanned and clean\n"),
    }
    for hostile in hostile_names():
        files[f"odd/{hostile}"] = ("100644", hostile.encode("utf-8", "surrogateescape") + b"\n")
    *edited, renamed = sb.cfg.follow_probe_paths
    for probe in edited:
        files[probe] = ("100644", f"v1 {probe}\n".encode())
    # The last probe starts under another name, so --follow must cross a rename
    # inside the ingester history as well as the relocation.
    files[f"before-rename/{renamed}"] = ("100644", f"v1 {renamed}\n".encode())
    root = sb.commit(repo, sb.tree(repo, files), [], "ingester root")
    second = {probe: ("100644", f"v2 {probe}\n".encode()) for probe in edited}
    if leak_in_history:
        second["docs/evidence/agent-run.log"] = ("100644", leak_sample())
    if merged_leak:
        # The mainline touches docs/evidence/ too, so the merge is not
        # TREESAME to the side branch there and the scanner diffs it.
        second["docs/evidence/main-note.md"] = ("100644", b"mainline note, clean\n")
    middle = sb.commit(repo, sb.tree(repo, second, base=f"{root}^{{tree}}"), [root], "ingester work")
    leaks = [middle] if leak_in_history else []
    third = {
        f"before-rename/{renamed}": ("0", b""),
        renamed: ("100644", f"v1 {renamed}\n".encode()),
    }
    if leak_in_history:
        third["docs/evidence/agent-run.log"] = ("0", b"")  # gone from the tip, still in history
    moved = sb.commit(repo, sb.tree(repo, third, base=f"{middle}^{{tree}}"), [middle], "ingester rename")
    # A side branch and a merge that resolves a probe to new content: plain
    # `git log -- <probe>` lists such a merge, `git log --follow` never does.
    clash = {edited[0]: ("100644", f"side {edited[0]}\n".encode())} if edited else {}
    if merged_leak:
        clash["docs/evidence/side-run.log"] = ("100644", leak_sample())
    side = sb.commit(repo, sb.tree(repo, clash, base=f"{root}^{{tree}}"), [root], "ingester side")
    resolved = {edited[0]: ("100644", f"merged {edited[0]}\n".encode())} if edited else {}
    if merged_leak:
        resolved["docs/evidence/side-run.log"] = ("100644", leak_sample())
    tip = sb.commit(repo, sb.tree(repo, resolved, base=f"{moved}^{{tree}}"), [moved, side], "ingester merge")
    if merged_leak:
        leaks += [side, tip]
    if late_leak:
        late = {"docs/evidence/late-run.log": ("100644", leak_sample())}
        tip = sb.commit(repo, sb.tree(repo, late, base=f"{tip}^{{tree}}"), [tip], "ingester work after the waiver")
        leaks.append(tip)
    sb.set_head(repo, tip)
    return Ingester(repo, root, tip, tuple(leaks))


@dataclass
class World:
    sb: Sandbox
    ta: Path
    ing: Ingester
    cfg: LayoutConfig
    base: str
    anchor: str
    branch: str

    @property
    def prefix(self) -> str:
        return self.cfg.ingester_prefix

    def fetch(self) -> None:
        self.sb.git(self.ta, "fetch", "-q", str(self.ing.path), "main")

    def tip_tree(self, changes: dict[str, tuple[str, bytes]] | None = None) -> str:
        base = f"{self.ing.tip}^{{tree}}"
        if not changes:
            return self.sb.git(self.ta, "rev-parse", base)
        return self.sb.tree(self.ta, changes, base=base)

    def relocate(self, subtree: str | None = None, prefix: str | None = None, parents: list[str] | None = None) -> str:
        nested = self.sb.nest(self.ta, prefix or self.prefix, subtree or self.tip_tree())
        return self.sb.commit(self.ta, nested, parents or [self.ing.tip], "chore: relocate ingester tree")

    def merge(self, first: str, second: str, subtree: str | None = None, swap: bool = False) -> str:
        tree = self.sb.graft(self.ta, first, self.prefix, subtree or self.tip_tree())
        parents = [second, first] if swap else [first, second]
        return self.sb.commit(self.ta, tree, parents, "Merge legal-corpus-ingester history")

    def app_commit(self, parent: str, changes: dict[str, tuple[str, bytes]], message: str) -> str:
        return self.sb.commit(self.ta, self.sb.tree(self.ta, changes, base=f"{parent}^{{tree}}"), [parent], message)

    def head(self, commit: str) -> None:
        self.sb.set_head(self.ta, commit)

    def waive(self, *shas: str) -> None:
        self.cfg = replace(self.cfg, waived_history_commits=shas)

    def repo(self) -> Repo:
        return Repo(self.ta, self.cfg)


