def test_scenario_table_contract() -> None:
    """Every check has the positive control and at least one negative."""
    positives = [name for name, s in SCENARIOS.items() if s.must_pass == ALL]
    assert positives, "no scenario passes every check"
    for scenario in SCENARIOS.values():
        assert set(scenario.must_fail) <= ALL and scenario.must_pass <= ALL
        assert not set(scenario.must_fail) & scenario.must_pass
    failed_somewhere = set().union(*(s.must_fail for s in SCENARIOS.values()))
    assert failed_somewhere == ALL, f"checks with no negative scenario: {sorted(ALL - failed_somewhere)}"


@pytest.mark.parametrize("name", list(SCENARIOS))
def test_sandbox_scenario(name: str, tmp_path: Path, ingesters: dict[str, Ingester]) -> None:
    scenario = SCENARIOS[name]
    world = make_world(tmp_path, ingesters[scenario.ingester])
    scenario.build(world)
    repo = world.repo()
    for check in sorted(scenario.must_pass):
        CHECKS[check](repo)
    for check, fragment in scenario.must_fail.items():
        with pytest.raises(CheckFailure) as caught:
            CHECKS[check](repo)
        message = str(caught.value)
        assert fragment in message, f"{check}: dishonest message {message!r}"
        assert all(" " <= ch <= "~" for ch in message), f"{check}: unescaped output {message!r}"
        assert str(tmp_path) not in message


