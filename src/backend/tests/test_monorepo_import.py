class ConfigError(ValueError):
    """monorepo-layout.conf is unusable; no check runs on a bad config."""


@dataclass(frozen=True)
class LayoutConfig:
    ingester_remote_url: str
    ingester_tip: str
    ingester_root_commit: str
    app_anchor: str
    ingester_prefix: str
    follow_probe_paths: tuple[str, ...]
    git_timeout_seconds: int
    max_git_output_bytes: int
    max_message_chars: int
    # Owner waiver (plan 4.7 option b, ruling 2026-10-15): ingester commits whose
    # own diff adds a local machine path under docs/evidence/. Full SHAs only;
    # a missing or empty key waives nothing.
    waived_history_commits: tuple[str, ...] = ()


CONFIG_KEYS = tuple(f.name for f in fields(LayoutConfig))
WAIVER_KEY = "waived_history_commits"
OPTIONAL_KEYS = (WAIVER_KEY,)
REQUIRED_KEYS = tuple(key for key in CONFIG_KEYS if key not in OPTIONAL_KEYS)
SHA_KEYS = ("ingester_tip", "ingester_root_commit", "app_anchor")
INT_KEYS = ("git_timeout_seconds", "max_git_output_bytes", "max_message_chars")
_SHA = re.compile(r"[0-9a-f]{40}")
_INT = re.compile(r"[1-9][0-9]*")
_SEGMENT = re.compile(r"[A-Za-z0-9._-]+")
_GITHUB_URL = re.compile(r"https://github\.com/([A-Za-z0-9_.-]+)/([A-Za-z0-9_.-]+)")


def _check_path(key: str, value: str) -> str:
    for number, part in enumerate(value.split("/"), start=1):
        if not _SEGMENT.fullmatch(part) or set(part) == {"."}:
            raise ConfigError(f"{key}: segment {number} is not a repo-relative path segment")
    return value


def parse_config(data: bytes) -> LayoutConfig:
    try:
        text = data.decode("ascii")
    except UnicodeDecodeError as exc:
        raise ConfigError(f"{CONFIG_REL}: byte {exc.start} is not ASCII") from None
    raw: dict[str, str] = {}
    for number, line in enumerate(text.split("\n"), start=1):
        bad = next((ch for ch in line if not " " <= ch <= "~"), None)
        if bad is not None:
            raise ConfigError(f"line {number}: character U+{ord(bad):04X} is not printable ASCII")
        if not line.strip() or line.startswith("#"):
            continue
        key, sep, value = line.partition("=")
        if not sep:
            raise ConfigError(f"line {number}: expected key=value")
        if key not in CONFIG_KEYS:
            raise ConfigError(f"line {number}: unknown key")
        if key in raw:
            raise ConfigError(f"line {number}: duplicate key {key}")
        if (not value and key not in OPTIONAL_KEYS) or value != value.strip():
            raise ConfigError(f"{key}: empty value or surrounding spaces")
        raw[key] = value
    missing = [key for key in REQUIRED_KEYS if key not in raw]
    if missing:
        raise ConfigError(f"missing key(s): {', '.join(missing)}")
    for key in SHA_KEYS:
        if not _SHA.fullmatch(raw[key]):
            raise ConfigError(f"{key}: not a full 40-hex lowercase commit id")
    if len({raw[key] for key in SHA_KEYS}) != len(SHA_KEYS):
        raise ConfigError(f"{', '.join(SHA_KEYS)} must be three different commits")
    ints: dict[str, int] = {}
    for key in INT_KEYS:
        if not _INT.fullmatch(raw[key]):
            raise ConfigError(f"{key}: not a positive decimal integer")
        ints[key] = int(raw[key])
    url = _GITHUB_URL.fullmatch(raw["ingester_remote_url"])
    if url is None or any(set(part) == {"."} for part in url.groups()):
        raise ConfigError("ingester_remote_url: not https://github.com/<owner>/<repo>")
    probes = tuple(raw["follow_probe_paths"].split(" "))
    for probe in probes:
        _check_path("follow_probe_paths", probe)
    if len(set(probes)) != len(probes):
        raise ConfigError("follow_probe_paths: duplicate path")
    # Exact full ids only: a short id or a prefix would waive any commit it
    # happens to abbreviate.
    waived = tuple(raw["waived_history_commits"].split(" ")) if raw.get("waived_history_commits") else ()
    for sha in waived:
        if not _SHA.fullmatch(sha):
            raise ConfigError("waived_history_commits: not space-separated full 40-hex lowercase commit ids")
    if len(set(waived)) != len(waived):
        raise ConfigError("waived_history_commits: duplicate commit id")
    return LayoutConfig(
        ingester_remote_url=raw["ingester_remote_url"],
        ingester_tip=raw["ingester_tip"],
        ingester_root_commit=raw["ingester_root_commit"],
        app_anchor=raw["app_anchor"],
        ingester_prefix=_check_path("ingester_prefix", raw["ingester_prefix"]),
        follow_probe_paths=probes,
        **ints,
        waived_history_commits=waived,
    )


def load_config() -> LayoutConfig:
    try:
        data = (REPO_ROOT / CONFIG_REL).read_bytes()
    except OSError:
        raise ConfigError(f"{CONFIG_REL} is missing or unreadable") from None
    return parse_config(data)


