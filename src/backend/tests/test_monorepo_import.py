def make_world(tmp_path: Path, ing: Ingester) -> World:
    real = load_config()
    sb = Sandbox(tmp_path, real)
    ta = sb.init("ta")
    base = sb.commit(ta, sb.tree(ta, {
        "README.md": ("100644", b"terms-analysis\n"),
        "src/backend/app/main.py": ("100644", b"app = 1\n"),
    }), [], "app root")
    world = World(sb, ta, ing, real, base, "", "")
    world.anchor = world.app_commit(base, {"src/backend/app/main.py": ("100644", b"app = 2\n")}, "app anchor")
    world.branch = world.app_commit(
        world.anchor, {"src/backend/tests/test_monorepo_import.py": ("100644", b"# red tests\n")}, "test: red"
    )
    # The real waiver names real ingester commits; a sandbox starts with none.
    world.cfg = replace(
        real, ingester_tip=ing.tip, ingester_root_commit=ing.root, app_anchor=world.anchor, waived_history_commits=()
    )
    sb.cfg = world.cfg
    world.head(world.branch)
    regex = ta / LEAK_REGEX_REL
    regex.parent.mkdir(parents=True)
    shutil.copyfile(REPO_ROOT / LEAK_REGEX_REL, regex)
    return world


